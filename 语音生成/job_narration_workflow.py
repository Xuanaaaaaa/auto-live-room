"""
Job narration workflow for live-stream job search demos.

Input:
  A JSON response from the job search backend.

Output:
  1. A short live narration script generated by a Doubao text model.
  2. An audio file generated by Doubao TTS.

The module is intentionally workflow-friendly:
  - Core functions can be imported by queue workers.
  - CLI can read from a file or stdin.
  - Provider settings come from env vars and CLI args.
"""


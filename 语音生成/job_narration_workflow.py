@dataclass
class JobPayload:
    id: Optional[Any]
    name: str
    company_name: str
    city: str
    company_type_key: str
    company_title_key: str
    start_time: str
    end_time: str
    recommended_message: str
    extra_fields: Dict[str, Any]
    raw: Dict[str, Any]


